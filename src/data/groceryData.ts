/**
 * Returns localized product fields based on active locale (Spanish default, English supported)
 */
export function getProductLocalized(product: GroceryProduct, locale?: string) {
  if (locale === "en") {
    return {
      name: product.nameEn || product.name,
      description: product.descriptionEn || product.description,
      unit: product.unitEn || product.unit,
      badge: product.badgeEn || product.badge,
      origin: product.originEn || product.origin,
    };
  }
  return {
    name: product.name,
    description: product.description,
    unit: product.unit,
    badge: product.badge,
    origin: product.origin,
  };
}

// Helper to get custom created products from localStorage
export function getCustomProducts(): GroceryProduct[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem("tailgrocery_custom_products");
    if (!raw) return [];
    const parsed: GroceryProduct[] = JSON.parse(raw);
    // Filter out dummy/stale test products from previous development
    return parsed.filter(
      (p) =>
        p &&
        p.id !== "g-01" &&
        !p.imageUrl?.includes("/images/product/") &&
        !p.imageUrl?.includes("images.unsplash.com") &&
        p.name !== "Fresh Vegetables Box"
    );
  } catch {
    return [];
  }
}

// Helper to get deleted product IDs from localStorage
export function getDeletedProductIds(): string[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem("tailgrocery_deleted_products");
    if (!raw) return [];
    return JSON.parse(raw);
  } catch {
    return [];
  }
}

// Get all products (custom products + default seed catalog, excluding deleted)
export function getAllProducts(): GroceryProduct[] {
  const deletedIds = new Set(getDeletedProductIds());
  const custom = getCustomProducts().filter((p) => !deletedIds.has(p.id));
  const customIds = new Set(custom.map((p) => p.id));
  return [
    ...custom,
    ...GROCERY_PRODUCTS.filter((p) => !customIds.has(p.id) && !deletedIds.has(p.id)),
  ];
}

// Save or update a product
export function saveProduct(product: GroceryProduct): GroceryProduct[] {
  if (typeof window === "undefined") return GROCERY_PRODUCTS;
  const deleted = getDeletedProductIds().filter((id) => id !== product.id);
  const custom = getCustomProducts();
  const existingIdx = custom.findIndex((p) => p.id === product.id);
  let updated: GroceryProduct[];
  if (existingIdx >= 0) {
    updated = [...custom];
    updated[existingIdx] = product;
  } else {
    updated = [product, ...custom];
  }
  try {
    localStorage.setItem("tailgrocery_deleted_products", JSON.stringify(deleted));
    localStorage.setItem("tailgrocery_custom_products", JSON.stringify(updated));
    window.dispatchEvent(new CustomEvent("grocery-products-updated"));
  } catch (e) {
    console.error("Failed to save product", e);
  }
  return getAllProducts();
}

// Bulk save products (e.g. from CSV import)
export function saveBulkProducts(newProducts: GroceryProduct[]): GroceryProduct[] {
  if (typeof window === "undefined") return GROCERY_PRODUCTS;
  const deleted = new Set(getDeletedProductIds());
  const newProductIds = new Set(newProducts.map((p) => p.id));
  const cleanedDeleted = Array.from(deleted).filter((id) => !newProductIds.has(id));
  const custom = getCustomProducts();
  const remaining = custom.filter((p) => !newProductIds.has(p.id));
  const updated = [...newProducts, ...remaining];
  try {
    localStorage.setItem("tailgrocery_deleted_products", JSON.stringify(cleanedDeleted));
    localStorage.setItem("tailgrocery_custom_products", JSON.stringify(updated));
    window.dispatchEvent(new CustomEvent("grocery-products-updated"));
  } catch (e) {
    console.error("Failed to save bulk products", e);
  }
  return getAllProducts();
}

// Delete a product (works for both custom and seed catalog products)
export function deleteProduct(productId: string): GroceryProduct[] {
  if (typeof window === "undefined") return GROCERY_PRODUCTS;
  const custom = getCustomProducts().filter((p) => p.id !== productId);
  const deleted = Array.from(new Set([...getDeletedProductIds(), productId]));
  try {
    localStorage.setItem("tailgrocery_custom_products", JSON.stringify(custom));
    localStorage.setItem("tailgrocery_deleted_products", JSON.stringify(deleted));
    window.dispatchEvent(new CustomEvent("grocery-products-updated"));
  } catch (e) {
    console.error("Failed to delete product", e);
  }
  return getAllProducts();
}
